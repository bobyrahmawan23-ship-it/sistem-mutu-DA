// Helper to calculate overall weighted score
export function calculateWeightedScore(scores: { criterionId: string; score: number }[]): number {
  if (!scores.length) return 0;
  const weights: Record<string, number> = {
    c1_tartil: 0.15,
    c2_kebiasaan_tilawah: 0.10,
    c3_hafalan_mutqin: 0.15,
    c4_ghorib_tajwid: 0.10,
    c5_irama_bayati: 0.10,
    c6_metode_maqdis: 0.15,
    c7_jiwa_dai_murobbi: 0.10,
    c8_disiplin_waktu: 0.10,
    c9_komitmen_mutu: 0.10,
  };

  let total = 0;
  let weightSum = 0;
  for (const item of scores) {
    const w = weights[item.criterionId] ?? 0.11;
    total += item.score * w;
    weightSum += w;
  }
  return Math.round((total / (weightSum || 1)) * 10) / 10;
}

