export function getQualityCategory(score: number): QualityCategory {
  if (score >= 89) return 'MUMTAZ';
  if (score >= 76) return 'JAYYID_JIDDAN';
  if (score >= 60) return 'JAYYID';
  return 'MAQBUL';
}

